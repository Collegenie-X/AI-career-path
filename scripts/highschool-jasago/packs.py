def highlight_stats(f):
    n = f['short']
    stats = []
    if f['rate']:
        stats.append({'label': '2026 경쟁률', 'value': f['rate'], 'emoji': '🔥', 'color': '#f97316'})
    else:
        stats.append({'label': '2026 경쟁률', 'value': '미공개', 'emoji': '🔍', 'color': '#94a3b8'})
    q = f['quota'] or f['quotaEstimate']
    stats.append({'label': '연 모집인원', 'value': f"{q}명" + ('' if f['quota'] else ' (추정)'), 'emoji': '🎟️', 'color': '#3b82f6'})
    stats.append({'label': '전체 재학생', 'value': f"{f['students']}명", 'emoji': '🧑‍🎓', 'color': '#8b5cf6'})
    if f['status'] == 'converted':
        stats.append({'label': '현재 지위', 'value': f"일반고 ({f['convertedYear']} 전환)", 'emoji': '🔄', 'color': '#64748b'})
    elif f['unit'] == '전국':
        stats.append({'label': '선발 범위', 'value': '전국 단위 · 기숙', 'emoji': '🌏', 'color': '#10b981'})
    else:
        stats.append({'label': '선발 범위', 'value': f"{f['sido'][:2]} 광역 · " + ('기숙 병설' if f['dorm'] else '통학'), 'emoji': '🗺️', 'color': '#10b981'})
    return stats


